<template>
  <div class="formPanel" ref="formPanel" style="margin-left: 15%;">
    <div class="form-item prod-panel" >
      <div class="title">
      </div>
      <DisplayAccountInfo ref="addProdForm" v-model="formData" :formData="formData"/>
    </div>
  </div>
</template>

<script>
  import DisplayAccountInfo         from "../../M81/prodDisplay/prodAccountInfo/DisplayAccountInfo.vue"
  export default {
    name: "AccountInfoFlow",
    components: {
      DisplayAccountInfo
    },
    props:{
      taskInfo: {},
    },
    data() {
      return {
        formData:{},
      }
    },
    created() {
      this.httpUtil
        .ajax({
          url: "/wf/formData/getSubmitParamsByProcessInstanceId.json",
          params: {processInstanceId: this.taskInfo.processInstanceId,_wfProcessInstanceId:this.taskInfo.processInstanceId}
        }).then(res => {
        if (res.data) {
          this.formData = JSON.parse(res.data.submitParams);
        }
      });

    },
  }
</script>

