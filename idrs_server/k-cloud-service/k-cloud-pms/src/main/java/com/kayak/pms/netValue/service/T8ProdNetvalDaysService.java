	/**
	 * 功能：自动跑批调用 每月28号跑 生成基准日期落在下个月的净值披露日期数据
	 * 作者：rennannan
	 * 日期：20210621
	 *
	 * @param params
	 * @throws Exception
	 */
	@API(desc = "自动跑批生成产品净值披露日期", auth = APIAuth.NO, operation = APIOperation.INSTER)
	public void autoGenerateDays(SqlParam<T8ProdNetvalDays> params) throws Exception {
		//获取当前日期
		String nowDate = DateUtil.getNowDate();

		//获取下月日期
		String nextMonthDate = DateUtil.calculation(nowDate, "yyyyMMdd", 1, Calendar.MONTH);
		//获取下月第一天与最后一天
		String nextMonthFirstDay = DateUtil.getFirstDayDateOfMonth(nextMonthDate);
		String nextMonthEndDate = DateUtil.getLastDayOfMonth(nextMonthDate);
		String month = nextMonthDate.substring(0, 6);
		List<T8ProdNetvalDays> netValueDays = getNetvalDaysList(nextMonthFirstDay, nextMonthEndDate, month);
		if (netValueDays.size() > 0) {
			addAndDelNetvalList(netValueDays, month);
		}
	}

	/**
	 * 功能：查询日期区间的产品净值披露日期
	 * 作者：rennannan
	 * 日期：20210621
	 *
	 * @param
	 * @param
	 * @return
	 * @throws Exception
	 */
	public List<T8ProdNetvalDays> getNetvalDaysList(String monthFirstDate, String monthEndDate, String month) throws Exception {
		//查询t8_disclosure_prod_rule表中信披类型为9（净值公告）且发起方式为时间规则发起的数据
		ScheduleProdRule prodRule = new ScheduleProdRule();
		prodRule.setDisclosureType("9");//信披类型  净值公告
		prodRule.setStartRule("2");//发起方式  时间规则发起
		List<ScheduleProdRule> prodRuleList = scheduleProdRuleDao.findProdRulesByType(prodRule);
		List<T8ProdNetvalDays> t8ProdNetvalDaysList = new ArrayList<>();

		//下个月的开始日期与结束日期
		String nextMonthDate = DateUtil.calculation(monthFirstDate, "yyyyMMdd", 1, Calendar.MONTH);//获取下个月日期
		String nextMonthStartDate = DateUtil.getFirstDayDateOfMonth(nextMonthDate);//获取下月最后一天
		String nextMonthEndDate = DateUtil.getLastDayOfMonth(nextMonthDate);

		//查询本月银行间工作日
		List<DisclosureWorkday> bankWorkDayList = getDealWorkDays("001", monthFirstDate, monthEndDate);

		//查询下月银行间第一个工作日
		String nextMonthBankDay = "";
		List<DisclosureWorkday> nextBankDayList = getDealWorkDays("001", nextMonthStartDate, nextMonthEndDate);
		if (nextBankDayList.size() > 0) {
			nextMonthBankDay = nextBankDayList.get(0).getWorkday();
		}

		//查询本月期间交易所工作日

		List<DisclosureWorkday> dealWorkDayList = getDealWorkDays("002", monthFirstDate, monthEndDate);

		//查询传入日期下个月期间交易所工作日
		List<DisclosureWorkday> dealTwoMonthWorkDayList = getDealWorkDays("002", nextMonthStartDate, nextMonthEndDate);

		for (ScheduleProdRule scheProdRule : prodRuleList) {
			t8ProdNetvalDaysList.addAll(getProdNetValList(scheProdRule, monthFirstDate, monthEndDate, dealWorkDayList, month, dealTwoMonthWorkDayList, bankWorkDayList, nextMonthBankDay));
		}
		return t8ProdNetvalDaysList;
	}

